// Regenerates tiers/*/cordis.patch.yml from the official presets of the running DSH build.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { engineModules, loadEngine, relaunchInDsh } from './dsh-runtime.ts'
import { buildTier, SOURCE_FILES, tierPatchFile, TIERS } from './tiers.ts'

relaunchInDsh(import.meta.url)

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const engine = await loadEngine()
const version: string = JSON.parse(
  readFileSync(join(engineModules(), '@deepseek-ai/dsh-app-boot/package.json'), 'utf8')).version

for (const tier of TIERS) {
  const patches = buildTier(tier, engine.modules, engine.loadOverlayPatches)
  const body = engine.yaml.dump(patches, { schema: engine.entryListSchema, lineWidth: -1, noRefs: true })
  const header = [
    `# Agent tier "${tier.name}" for dsh-agent-tiers. GENERATED by scripts/generate.ts - do not edit.`,
    `# Source: ${SOURCE_FILES[tier.source]} from DSH ${version}.`,
    `# Change the tier in scripts/tiers.ts, then run: npm run generate`,
    '',
  ].join('\n')
  const file = join(root, tierPatchFile(tier.folder))
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, header + body)
  console.log(`wrote ${tierPatchFile(tier.folder)} (${patches[0].insert[0].config.plugins.length} plugin rows)`)
}
